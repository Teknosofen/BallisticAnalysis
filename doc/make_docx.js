function table(head, rows, widths, opts = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (t, w, o = {}) => new TableCell({
    width: { size: w, type: WidthType.DXA },
    shading: o.head ? { type: ShadingType.CLEAR, fill: 'F1F0EC' } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    borders: {
      top: { style: BorderStyle.SINGLE, size: o.head ? 4 : 2, color: o.head ? 'C3C2B7' : 'E1E0D9' },
      bottom: { style: BorderStyle.SINGLE, size: o.head ? 6 : 2, color: o.head ? 'C3C2B7' : 'E1E0D9' },
      left: { style: BorderStyle.NONE }, right: { style: BorderStyle.NONE },
    },
    children: [new Paragraph({
      children: typeof t === 'string'
        ? [new TextRun({ text: t, bold: !!o.head, size: 17,
                         color: o.head ? INK : SEC })]
        : t,
      alignment: o.align, spacing: { after: 0, line: 240 },
    })],
  });
  const alignOf = i => (opts.leftCols && i < opts.leftCols)
    ? AlignmentType.LEFT : AlignmentType.RIGHT;
  return new Table({
    columnWidths: widths,
    width: { size: total, type: WidthType.DXA },
    rows: [
      new TableRow({ tableHeader: true, children:
        head.map((t, i) => cell(t, widths[i], { head: true, align: alignOf(i) })) }),
      ...rows.map(r => new TableRow({ children:
        r.map((t, i) => cell(t, widths[i], { align: alignOf(i) })) })),
    ],
  });
}

