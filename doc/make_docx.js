/* ---------------------------------------------------- 11. limitations ----- */
P(new Paragraph({ children: [new PageBreak()] }));
P(h1('11  Model compromises and upgrade paths'));
P(p('This section states what the lumped-parameter formulation gives up, and what the next '
  + 'model up the ladder would buy. They are ordered by cost.'));

P(h2('11.1  What the lumped model assumes away'));
P(p([bd('No wave dynamics. '), tx('Assumption A1 replaces a compressible gas column with a '
  + 'single control volume. Real ignition is not simultaneous: the primer jet ignites the '
  + 'rear of the charge first and a combustion front sweeps forward, generating pressure '
  + 'waves that traverse the chamber several times during the shot. In small arms these are '
  + 'of order a few per cent of the peak pressure and decay quickly, so the lumped model is '
  + 'defensible; in large guns they are a design driver and can be destructive.')]));
P(p([bd('No two-phase flow. '), tx('Assumption A5 makes the solid grains ride with the gas. '
  + 'In reality the grain bed is compacted by the initial pressure gradient, gas percolates '
  + 'through it, and the grains near the bullet base move at a different velocity from those '
  + 'at the breech. This is what a two-phase model resolves.')]));
P(p([bd('Fixed thermochemistry. '), tx('Assumption A3 holds f, T_v, α and γ constant. At '
  + '2850 K and 400 MPa the combustion products are partly dissociated, and both γ and the '
  + 'effective impetus vary through the cycle. An equilibrium-chemistry code such as BLAKE '
  + 'or CHEETAH would supply p- and T-dependent properties.')]));
P(p([bd('Crude bore resistance. '), tx('Assumption A7 is the weakest of the physical '
  + 'submodels. Measured bore resistance has a sharp engraving spike over the first few '
  + 'millimetres, then falls, then rises again with velocity as viscous and thermal effects '
  + 'in the bullet–bore interface grow. A constant p_r cannot capture the late rise, which '
  + 'is precisely why the model does not reproduce the observed velocity roll-over beyond '
  + 'about 20 in.')]));
P(p([bd('No leakage, no bullet dynamics. '), tx('Assumption A9 ignores blow-by past an '
  + 'imperfectly obturating bullet and any change in the bullet’s length or diameter '
  + 'under 400 MPa of base pressure and 195 000 g of acceleration. Both would reduce the '
  + 'delivered impulse slightly and, importantly, both would tend to lower the computed '
  + 'muzzle pressure — a candidate explanation for the short-barrel discrepancy in §9.2.')]));

P(h2('11.2  Level 1.5 — the Lagrange gradient (already included)'));
P(p([tx('The cheapest possible improvement over a strictly uniform-pressure model is the '
  + 'Lagrange gradient of §4.6, and it is included here because it costs three lines of '
  + 'algebra and no computation at all. It converts a single pressure into a physically '
  + 'meaningful spatial distribution, which is what makes it possible to report breech, mean '
  + 'and base pressures separately — and to compute a gas-port pressure. For a cartridge '
  + 'with ζ = 0.40 the effect is a 20 % spread between breech and base, so it is not '
  + 'optional at this charge-to-mass ratio.')]));
P(p([bd('What it still cannot do: '), tx('the Lagrange profile is a quasi-steady '
  + 'approximation. It has no wave content, and it assumes uniform gas density along the '
  + 'column, which is poor while the charge is still burning and gas is being created '
  + 'preferentially where the grains are.')]));

P(h2('11.3  Level 2 — one-dimensional gas dynamics'));
P(p([tx('The next step replaces the control volume with the one-dimensional Euler equations '
  + 'for the gas column, solved on a moving mesh between the breech face and the bullet base '
  + 'with a shock-capturing scheme. Mass, momentum and energy are conserved locally, with '
  + 'the propellant burn appearing as a distributed source term.')]));
P(p([bd('What it buys: '), tx('genuine pressure waves and their reflections; a correct '
  + 'density distribution; a proper treatment of progressive ignition if the igniter is '
  + 'modelled as a distributed source; and — most relevant here — a physically-based rather '
  + 'than assumed pressure at any station, including the gas port and the muzzle.')]));
P(p([bd('What it costs: '), tx('roughly three orders of magnitude more computation than the '
  + 'present model, and it introduces mesh and scheme dependence that must itself be '
  + 'verified. It would not run interactively in a browser.')]));

P(h2('11.4  Level 3 — two-phase reactive flow'));
P(p([tx('The reference formulation used in modern gun design (NGEN, XKTC, and their '
  + 'descendants) treats gas and solid propellant as two interpenetrating continua, each '
  + 'with its own velocity, with mass, momentum and energy exchange between them, '
  + 'intergranular stress in the packed bed, and a resolved ignition front.')]));
P(p([bd('What it buys: '), tx('the ability to predict ignition-related phenomena that the '
  + 'lumped model cannot represent at all — hangfires, pressure-wave-driven overpressure, '
  + 'the effect of charge-bed settling and of primer output on round-to-round variation. For '
  + 'small arms it is the tool of choice when the question is about ignition robustness '
  + 'rather than about mean performance.')]));
P(p([bd('What it costs: '), tx('a substantially larger parameter set — interphase drag, '
  + 'intergranular stress law, grain-bed permeability — most of which is not published for '
  + 'commercial propellants and must be measured. For the barrel-length question posed here '
  + 'it would add cost without adding accuracy.')]));

